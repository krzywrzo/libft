#include "libft.h"

int	ft_isalpha(int ltr)
{
	if ((ltr >= 'a' && ltr <= 'z') || (ltr >= 'A' && ltr <= 'Z'))
	{
		return (1);
	}
	else
	{
		return (0);
	}
}
